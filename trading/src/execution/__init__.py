"""執行基盤。

## 記憶に頼らない

「昨日どのポジションを持っていたか」は、**取引所に聞けば分かる**。
ローカルに持った記憶と実際の保有がずれたとき、正しいのは常に取引所の側になる。

だからこの基盤は、**毎回かならず取引所から現在の保有を読み直す**。
前回の実行結果を信用しない。プロセスが落ちても、記憶が消えても、
別のマシンから動かしても、同じ判断になる。

これは「記憶がないから仕方なく」ではなく、**そのほうが安全だから**そうしている。
手で1回売買しただけで、記憶を持つ設計は壊れる。

## 目標との差分だけを出す

戦略が出すのは「どの銘柄をいくら持つべきか」（目標）だけにする。
そこから実際の注文を作るのは、目標と現在の保有の差分になる。

この形にすると、二重発注が構造的に起きない。
同じ処理を2回走らせても、1回目で目標に到達していれば2回目の差分はゼロになる。

## 検証を通っていないものは本番で動かさない

安全装置をドキュメントに書くだけでは守られない。**コードで拒否する。**
`guards.py` が、事前登録した検定の合格記録を要求する。
記録がない・不合格・古すぎる、のいずれかなら本番モードは起動しない。
"""
